const landmarksPath = path.join(__dirname, '..', '交互代码', '主app代码', '2026EL-main', 'src', 'main', 'resources', 'static', 'app', 'landmarks-data.js');
const raw = fs.readFileSync(landmarksPath, 'utf8');
const match = raw.match(/window\.NANJING_LANDMARKS = (\[[\s\S]*?\]);/);
if (!match) { console.log('Failed to parse landmarks-data.js'); process.exit(1); }

const landmarks = JSON.parse(match[1]);
let fixed = 0;
let notFound = [];

landmarks.forEach(l => {
  if (VERIFIED[l.name]) {
    const oldLng = l.lng;
    const oldLat = l.lat;
    l.lng = VERIFIED[l.name][0];
    l.lat = VERIFIED[l.name][1];
    const dist = Math.sqrt(Math.pow(l.lng - oldLng, 2) + Math.pow(l.lat - oldLat, 2)) * 111000;
    if (dist > 100) {
      console.log(`FIXED ${l.name}: [${oldLng}, ${oldLat}] -> [${l.lng}, ${l.lat}] (${dist.toFixed(0)}m)`);
      fixed++;
    }
  } else {
    notFound.push(l.name);
    console.log(`UNKNOWN ${l.name}: keeping [${l.lng}, ${l.lat}]`);
  }
});

console.log(`\nFixed: ${fixed}/${landmarks.length}`);
if (notFound.length) console.log('Not in verified DB:', notFound);

// Write updated
const newData = raw.replace(
  /window\.NANJING_LANDMARKS = \[[\s\S]*?\];/,
  'window.NANJING_LANDMARKS = ' + JSON.stringify(landmarks, null, 2) + ';'
);
fs.writeFileSync(landmarksPath, newData, 'utf8');
console.log('Updated:', landmarksPath);
