// Helper: merge landmarks with CITYGO_BUILDING_POINTS
window.getNanjingLandmarkPOIs = function() {
  var existing = Array.isArray(window.CITYGO_BUILDING_POINTS) ? window.CITYGO_BUILDING_POINTS : [];
  var existingNames = new Set(existing.map(function(p) { return p.name; }));
  var newLandmarks = window.NANJING_LANDMARKS
    .filter(function(l) { return !existingNames.has(l.name); })
    .map(function(l, i) {
      return {
        id: l.id,
        name: l.name,
        lng: l.lng, lat: l.lat,
        category: l.category,
        icon: "",
        address: l.address || "",
        intro: l.intro || "",
        image: l.image || "",
        tags: l.tags || [l.category, "南京"],
        kind: "building",
        locatorLabel: String(existing.length + i + 1).padStart(2, "0")
      };
    });
  return existing.concat(newLandmarks);
};
